function check=phase5f_refine_convergence(name)
% Follow-up to FAILED10us-vs5us trajectory checks; retain original evidence.
% Compare saved5us trajectory with independently rerun2.5us trajectory.
assert(any(strcmp(name,{'motor_cold_start','motor_direct_connection'})), ...
    'VSG:RefinementCase','Only the two declared convergence cases are supported.');
root=fileparts(mfilename('fullpath')); out=fullfile(root,'validation_outputs','stage5f');
original=jsondecode(fileread(fullfile(out,'validation_stage5f.json')));
vsg_assert_source_identity(original.source_identity);
loaded=load(fullfile(out,[name '_fine.mat'])); coarse=loaded.result;
p=coarse.parameters; p.integration_step=p.integration_step/2;
identity=vsg_source_identity({[mfilename('fullpath') '.m']});
result=vsg_motor_run_case(name,p);
n=min(numel(coarse.time),numel(result.time)); delta=abs(coarse.data(1:n,:)-result.data(1:n,:));
checks=struct('same_termination',strcmp(coarse.metrics.termination,result.metrics.termination), ...
    'same_duration',abs(coarse.time(end)-result.time(end))<=p.Ts+1e-10, ...
    'voltage',max(max(delta(:,1:2)))<0.05,'bus',max(delta(:,6))<0.05, ...
    'current',max(max(delta(:,3:4)))<0.05,'speed',max(delta(:,8))<0.5, ...
    'fine_numerical',result.metrics.numerical_checks_pass);
check=struct('scenario',name,'pass',all(structfun(@(v)logical(v),checks)), ...
    'checks',checks,'coarse_step',coarse.parameters.integration_step,'fine_step',p.integration_step, ...
    'max_voltage_difference',max(max(delta(:,1:2))),'max_bus_difference',max(delta(:,6)), ...
    'max_current_difference',max(max(delta(:,3:4))),'max_speed_difference',max(delta(:,8)), ...
    'original_source_identity',original.source_identity,'refinement_source_identity',identity, ...
    'original_10us_comparison',original.convergence.(name));
vsg_assert_source_identity(original.source_identity); vsg_assert_source_identity(identity);
save(fullfile(out,[name '_refined.mat']),'result','-v7');
fid=fopen(fullfile(out,[name '_refinement.json']),'w'); assert(fid>=0);
fprintf(fid,'%s',jsonencode(check)); fclose(fid);
fprintf('REFINEMENT %s: pass=%d voltage_delta=%.9g speed_delta=%.9g\n', ...
    name,check.pass,check.max_voltage_difference,check.max_speed_difference);
end
