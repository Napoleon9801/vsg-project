function vsg_assert_stage5c(model)
% Reject a stale baseline model; numeric constants were rounded by num2str.
spec={ 'Gain_Vinv_a','Gain',20; 'Gain_Vinv_b','Gain',20; ...
    'Gain_Vinv_c','Gain',20; 'V_set','Value',14; 'P_set','Value',1; ...
    'Gain_D','Gain',0.5; 'Gain_inv_2Hws','Gain',2*pi*50/(2*5); ...
    'Gain_droop_pf','Gain',-1/(0.05*2*pi*50); ...
    'Gain_qv','Gain',-0.05*14/100; ...
    'Gain_inv_Lf','Gain',1/1.2e-3; 'Gain_inv_Cf','Gain',1/10e-6; ...
    'Gain_Rf_lc','Gain',0.05; 'Gain_Rd','Gain',1; ...
    'Gain_inv_Lload','Gain',1000; 'R_load_step','Before',2.94; ...
    'R_load_step','After',2.94*0.7; 'R_load_step','Time',1; ...
    'PI_V_d','P',2*0.707*628*10e-6; 'PI_V_d','I',628^2*10e-6; ...
    'PI_I_d','P',6283*1.2e-3; 'PI_I_d','I',6283*0.05; ...
    'PI_V_q','P',2*0.707*628*10e-6; 'PI_V_q','I',628^2*10e-6; ...
    'PI_I_q','P',6283*1.2e-3; 'PI_I_q','I',6283*0.05};
for k=1:size(spec,1)
    actual=str2double(get_param([model '/' spec{k,1}],spec{k,2}));
    expected=spec{k,3};
    assert(isfinite(actual) && abs(actual-expected)<=max(1e-7,abs(expected)*1e-4), ...
        'VSG:BaselineParameter','Stale baseline: %s.%s expected %.12g, found %.12g', ...
        spec{k,1},spec{k,2},expected,actual);
end
end
