function vsg_assert_firmware_parameters(path,p)
% Refuse to label this model a parameter mirror when firmware constants drift.
text=fileread(path);
spec={'Ts',p.Ts;'Vdc',p.Vnom;'V_SET',p.Vset;'Lf',p.Lf;'Rf',p.Rf; ...
    'Cf',p.Cf;'H_INERTIA',p.H;'D_DAMP',p.D;'R_P',p.Rp;'R_Q',0.05; ...
    'P_BASE',p.Pbase;'Q_BASE',100;'P_SET_PU',1;'K_lpf',p.Klpf; ...
    'Kp_v',p.Kpv;'Ki_v_Ts',p.KivTs;'Kp_i',p.Kpi;'Ki_i_Ts',p.KiiTs; ...
    'Iref_max',p.Iref;'Vmax',p.Vmax;'I_TRIP_LIMIT',p.trip_current; ...
    'I_SQ_RATED',p.thermal_rated_mean_square;'THERMAL_TRIP',p.thermal_limit};
for k=1:size(spec,1)
    token=regexp(text,['const\s+float\s+' spec{k,1} '\s*=\s*([-+0-9.eE]+)f?\s*;'],'tokens');
    assert(numel(token)==1,'VSG:FirmwareParameter','Missing/ambiguous numeric constant %s',spec{k,1});
    value=str2double(token{1}{1});
    assert(abs(value-spec{k,2})<1e-10,'VSG:FirmwareParameter', ...
        'Firmware %s=%.12g differs from model %.12g',spec{k,1},value,spec{k,2});
end
end
