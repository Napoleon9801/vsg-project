function report = phase5f_motor_realism(output_dir)
% Stage 5f: averaged electromechanical motor study, MATLAB R2018b.
% No claim of measured motor identity, switch-waveform fidelity or hardware approval.
root=fileparts(mfilename('fullpath'));
if nargin<1; output_dir=fullfile(root,'validation_outputs','stage5f'); end
if ~exist(output_dir,'dir'); mkdir(output_dir); end
p=vsg_motor_parameters();
firmware=fullfile(root,'..','hardware','esp32','vsg_controller','vsg_controller.ino');
vsg_assert_firmware_parameters(firmware,p);
sources={'phase5f_motor_realism.m','vsg_motor_parameters.m','vsg_motor_rhs.m', ...
    'vsg_motor_plant_rhs.m','vsg_motor_run_case.m','test_vsg_motor.m', ...
    'vsg_firmware_control_step.m','vsg_assert_firmware_parameters.m'};
paths=cellfun(@(f)fullfile(root,f),sources,'UniformOutput',false); paths{end+1}=firmware;
identity=vsg_source_identity(paths);
tests=runtests(fullfile(root,'test_vsg_motor.m'));
assert(all([tests.Passed]),'VSG:MotorUnitTests','Motor physical invariant tests failed.');
cases={'rl_reference','motor_cold_start','motor_direct_connection','motor_torque_step', ...
    'motor_locked_rotor','motor_source_limit','motor_nonideal'};
report=struct('schema_version',1,'scope','Averaged induction-motor feasibility study; hypothetical machine', ...
    'parameters',p,'source_identity',identity,'unit_tests',struct('passed',sum([tests.Passed]), ...
    'failed',sum([tests.Failed]),'incomplete',sum([tests.Incomplete])), ...
    'cases',struct(),'convergence',struct());
saved=cell(size(cases));
for c=1:numel(cases)
    result=vsg_motor_run_case(cases{c},p); saved{c}=result;
    report.cases.(cases{c})=result.metrics;
    path=fullfile(output_dir,[cases{c} '.mat']); vsg_backup_output(path);
    save(path,'result','-v7');
    fprintf('[Stage 5f] %s: numerical=%d, %s at %.4fs, rpm=%.1f, shaft=%.2fW, busmin=%.3fV, Ipk=%.3fA\n', ...
        cases{c},result.metrics.numerical_checks_pass,result.metrics.termination,result.metrics.actual_duration, ...
        result.metrics.final_rpm,result.metrics.final_shaft_load_power,result.metrics.minimum_bus, ...
        result.metrics.peak_inverter_current);
end
for idx=[2,3]
    fine=p; fine.integration_step=p.integration_step/2;
    result=vsg_motor_run_case(cases{idx},fine); coarse=saved{idx};
    n=min(numel(coarse.time),numel(result.time));
    delta=abs(coarse.data(1:n,:)-result.data(1:n,:));
    checks=struct('same_termination',strcmp(coarse.metrics.termination,result.metrics.termination), ...
        'same_duration',abs(coarse.time(end)-result.time(end))<=p.Ts+1e-10, ...
        'voltage',max(max(delta(:,1:2)))<0.05,'bus',max(delta(:,6))<0.05, ...
        'current',max(max(delta(:,3:4)))<0.05,'speed',max(delta(:,8))<0.5, ...
        'fine_numerical',result.metrics.numerical_checks_pass);
    report.convergence.(cases{idx})=struct('pass',all(structfun(@(v)logical(v),checks)), ...
        'checks',checks,'coarse_step',p.integration_step,'fine_step',fine.integration_step, ...
        'max_voltage_difference',max(max(delta(:,1:2))),'max_bus_difference',max(delta(:,6)), ...
        'max_current_difference',max(max(delta(:,3:4))),'max_speed_difference',max(delta(:,8)));
    save(fullfile(output_dir,[cases{idx} '_fine.mat']),'result','-v7');
    fprintf('[Stage 5f] convergence %s: pass=%d\n',cases{idx},report.convergence.(cases{idx}).pass);
end
report.pass=all(structfun(@(r)r.numerical_checks_pass,report.cases)) && ...
    all(structfun(@(r)r.pass,report.convergence));
report.pass_meaning='Numerical/physical invariant checks only; read termination and motor_running separately.';
report.limitations=['Hypothetical unsaturated symmetric induction motor; fan torque law, no measured motor; ' ...
    'averaged bridge with phase duty clipping/one-tick stationary hold, no PWM ripple/THD; ' ...
    'no ADC timing/quantization, common-mode sensing, core loss/temperature/saturation or gate-driver physics; ' ...
    'source-only40V,0.3ohm,4A,2200uF assumed; nonideal conduction/deadtime approximations; ' ...
    'fault/model-boundary stops integration, not simulated safe shutdown; fixed50Hz VSG is not V/f or FOC; ' ...
    'integration-step check does not validate controller sample timing or identify a real motor'];
vsg_assert_source_identity(identity);
path=fullfile(output_dir,'validation_stage5f.json'); vsg_backup_output(path);
fid=fopen(path,'w'); assert(fid>=0); fprintf(fid,'%s',jsonencode(report)); fclose(fid);
assert(report.pass,'VSG:Stage5fChecks','Stage5f numerical/physics checks failed; inspect saved report.');
end
