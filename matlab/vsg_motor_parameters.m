function p = vsg_motor_parameters()
% Hypothetical low-voltage machine, NOT a commercial motor rating/datasheet.
% All inductances are referred-to-stator SI values, amplitude-invariant dq.
p=struct('Ts',1e-4,'integration_step',1e-5,'duration',6,'event',3, ...
    'Lf',1.2e-3,'Rf',0.05,'Cf',10e-6,'Rd',1,'Ll',1e-3,'Rload',2.94, ...
    'Kpv',0.00887592,'KivTs',0.000394384,'Kpi',7.5396,'KiiTs',0.031415, ...
    'Iref',10,'Vmax',20,'Vnom',40,'Vset',14,'w0',2*pi*50, ...
    'H',5,'D',0.5,'Rp',0.05,'Dq',0.007,'Pbase',100,'Klpf',0.00313176, ...
    'Cdc',2200e-6,'Rsource',0.30,'Isource',4,'delay',1, ...
    'Rbridge',0,'deadtime',0,'duty_min',0.03,'duty_max',0.97, ...
    'trip_current',10,'thermal_rated_mean_square',11.34,'thermal_limit',20, ...
    'minimum_bus',10,'maximum_bus',48,'torque_multiplier',1, ...
    'connected_at',0,'locked',false,'load_kind','motor');
p.motor=struct('Rs',0.8,'Rr',0.6,'Lls',3e-3,'Llr',3e-3,'Lm',60e-3, ...
    'pole_pairs',2,'Jm',2e-4,'B',1e-5,'omega_nominal',150, ...
    'mechanical_power_nominal',25,'load_sign_speed',1);
p.motor.Ls=p.motor.Lls+p.motor.Lm;
p.motor.Lr=p.motor.Llr+p.motor.Lm;
p.motor.determinant=p.motor.Ls*p.motor.Lr-p.motor.Lm^2;
assert(p.motor.determinant>0,'VSG:MotorInductance','Inductance matrix must be positive definite.');
p.assumptions=['Hypothetical unsaturated linear symmetric squirrel-cage motor; no measured rating; ' ...
    'Rs/Rr constant, no core loss, no skin effect; fan load25W at150rad/s; ' ...
    '40V source-only supply,0.30ohm,2200uF are study assumptions, not measured BESS'];
end
